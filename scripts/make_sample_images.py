OUT = Path(__file__).resolve().parent.parent / "sample_data" / "images"
W, H, S = 1600, 1066, 2  # output size, supersampling factor


def vgrad(size, top, bottom):
    w, h = size
    t = np.linspace(0, 1, h)[:, None, None]
    a = np.array(top)[None, None, :] * (1 - t) + np.array(bottom)[None, None, :] * t
    return Image.fromarray(np.repeat(a, w, axis=1).astype("uint8"), "RGB")


def finish(img, seed):
    img = img.resize((W, H), Image.LANCZOS).filter(ImageFilter.GaussianBlur(0.6))
    rng = np.random.default_rng(seed)
    a = np.asarray(img).astype("float32")
    yy, xx = np.mgrid[0:H, 0:W]
    vig = 1 - 0.22 * (((xx - W / 2) / (W / 2)) ** 2 + ((yy - H / 2) / (H / 2)) ** 2) / 2
    a = a * vig[..., None] + rng.normal(0, 3.2, a.shape)
    return Image.fromarray(np.clip(a, 0, 255).astype("uint8"))


def new(top, bottom):
    return vgrad((W * S, H * S), top, bottom)


def R(d, box, fill, r=0):
    x0, y0, x1, y1 = [int(v * S) for v in box]
    (d.rounded_rectangle if r else d.rectangle)((x0, y0, x1, y1), fill=fill, **({"radius": r * S} if r else {}))


def E(d, box, fill):
    d.ellipse([int(v * S) for v in box], fill=fill)


def P(d, pts, fill):
    d.polygon([(int(x * S), int(y * S)) for x, y in pts], fill=fill)


def tree(d, x, y, s, col=(46, 120, 74)):
    R(d, (x - 6 * s, y - 60 * s, x + 6 * s, y), (92, 64, 44))
    for dx, dy, r in ((0, -110, 52), (-34, -80, 40), (34, -80, 40), (0, -70, 46)):
        E(d, (x + (dx - r) * s, y + (dy - r) * s, x + (dx + r) * s, y + (dy + r) * s), col)


